#!/usr/bin/env python3
"""Build standalone bundles of every skill into dist/.

For each skills/<domain>/<product>/SKILL.md this writes:
  dist/<product>/      an installable skill folder: the skill's files plus a copy of core/
  dist/<product>.md    a single file: skill + its incident response + references + all of core

Usage:
  scripts/build-dist.py           rebuild dist/
  scripts/build-dist.py --check   exit 1 if dist/ is out of date (nothing is written)
"""
import filecmp
import re
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CORE_ORDER = [
    "modes-and-authorization.md",
    "operating-principles.md",
    "vulnerability-triage.md",
    "evidence-and-reporting.md",
    "tool-use-contract.md",
    "incident-response.md",
]
SKILL_PARTS = ["SKILL.md", "incident-response.md", "references.md"]
LOCAL_LINK = re.compile(r"\[([^\]]+)\]\((?!https?:)([^)#\s]+\.md)\)")
GENERATED = "<!-- Generated by scripts/build-dist.py. Edit the sources in skills/ and core/, not this file. -->\n"


def add_banner(text):
    # Keep YAML frontmatter first so skill loaders still recognize it.
    if text.startswith("---\n"):
        end = text.index("\n---\n", 4) + 5
        return text[:end] + "\n" + GENERATED + text[end:]
    return GENERATED + "\n" + text


def build(out):
    core_dir = ROOT / "core"
    core_files = [core_dir / name for name in CORE_ORDER]
    for skill_md in sorted(ROOT.glob("skills/*/*/SKILL.md")):
        src = skill_md.parent
        product = src.name

        # Installable folder: core links point at the bundled core/ copy.
        folder = out / product
        (folder / "core").mkdir(parents=True)
        for part in SKILL_PARTS:
            if (src / part).exists():
                text = (src / part).read_text().replace("../../../core/", "core/")
                (folder / part).write_text(add_banner(text))
        for f in core_files:
            (folder / "core" / f.name).write_text(GENERATED + "\n" + f.read_text())

        # Single file: every local link refers to a section that is included below.
        sections = [(src / p).read_text() for p in SKILL_PARTS if (src / p).exists()]
        sections += [f.read_text() for f in core_files]
        body = "\n\n---\n\n".join(LOCAL_LINK.sub(r"\1 (included in this file)", s.strip()) for s in sections)
        (out / f"{product}.md").write_text(add_banner(body + "\n"))


def same_tree(a, b):
    cmp = filecmp.dircmp(a, b)
    if cmp.left_only or cmp.right_only or cmp.funny_files:
        return False
    _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
    return not mismatch and not errors and all(same_tree(a / d, b / d) for d in cmp.common_dirs)


def main():
    dist = ROOT / "dist"
    if "--check" in sys.argv[1:]:
        with tempfile.TemporaryDirectory() as tmp:
            fresh = Path(tmp) / "dist"
            fresh.mkdir()
            build(fresh)
            if dist.is_dir() and same_tree(fresh, dist):
                print("build-dist: dist/ is up to date.")
                return 0
        print("build-dist: dist/ is out of date. Run scripts/build-dist.py.")
        return 1
    if dist.exists():
        shutil.rmtree(dist)
    dist.mkdir()
    build(dist)
    print(f"build-dist: wrote {', '.join(sorted(p.name for p in dist.iterdir()))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
